# Generates services/deskd/src/europe.rs from Natural Earth 1:50m countries (GeoJSON):
#   python3 -I xtask/europe.py ne_50m_admin_0_countries.geojson services/deskd/src/europe.rs
import json, sys, math
d=json.load(open(sys.argv[1]))
W,E,S_,N=-32.0,45.0,27.0,72.0
def dp(pts,eps):
    if len(pts)<3: return pts
    a,b=pts[0],pts[-1]; dmax=0; idx=0
    ax,ay=a; bx,by=b; L=math.hypot(bx-ax,by-ay) or 1e-12
    for i,(x,y) in enumerate(pts[1:-1],1):
        dd=abs((bx-ax)*(ay-y)-(ax-x)*(by-ay))/L
        if dd>dmax: dmax,idx=dd,i
    if dmax>eps:
        return dp(pts[:idx+1],eps)[:-1]+dp(pts[idx:],eps)
    return [a,b]
rings=[]
for f in d['features']:
    cc=f['properties']['ISO_A2_EH']
    if len(cc)!=2: continue
    g=f['geometry']; polys=g['coordinates'] if g['type']=='MultiPolygon' else [g['coordinates']]
    for poly in polys:
        ring=poly[0]
        xs=[p[0] for p in ring]; ys=[p[1] for p in ring]
        if max(xs)<W or min(xs)>E or max(ys)<S_ or min(ys)>N: continue
        pts0=[(p[0],p[1]) for p in ring]
        far=max(range(len(pts0)),key=lambda i:(pts0[i][0]-pts0[0][0])**2+(pts0[i][1]-pts0[0][1])**2)
        r=dp(pts0[:far+1],0.08)[:-1]+dp(pts0[far:],0.08)
        q=[]
        for x,y in r:
            pt=(round(x*100),round(y*100))
            if not q or q[-1]!=pt: q.append(pt)
        area=abs(sum(q[i][0]*q[i-1][1]-q[i-1][0]*q[i][1] for i in range(len(q))))/2
        if len(q)>=4 and area>=1500: rings.append((cc,q))
pts=sum(len(r) for _,r in rings)
out=['//! Europe and its neighbours, 32° W to 45° E and 27° N to 72° N: every',
'//! country\'s outline at 1:50m from Natural Earth (public domain,',
'//! naturalearthdata.com, `ne_50m_admin_0_countries`), simplified to 0.08°, with',
'//! islands under 0.15 square degrees dropped. Points are (longitude, latitude)',
'//! in hundredths of a degree, so no float is needed to draw or test them.',
'//! Generated by `xtask/europe.py` from the `GeoJSON`; the outline changes when a', '//! border does.','',
'/// Every ring, with the ISO 3166-1 alpha-2 code of the country it bounds.','#[rustfmt::skip]','pub const RINGS: &[(&str, &[(i16, i16)])] = &[']
for cc,r in rings:
    out.append(f'    ("{cc}", &['+', '.join(f'({x}, {y})' for x,y in r)+']),')
out.append('];')
open(sys.argv[2],'w').write('\n'.join(out)+'\n')
print(len(rings),'rings',pts,'points')
