//! Credentials for standalone customer sign-in.
use std::collections::BTreeMap;

use sha2::{Digest as _, Sha256};

use super::{Env, EnvRef, EstateError};
use crate::config::Secret;
use crate::{Operators, Token};

/// A stable customer subject and the environment variable holding its sign-in key.
#[derive(Clone, Debug, serde::Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(deny_unknown_fields)]
pub struct PortalUser {
    /// Immutable opaque subject, distinct from a payer, agreement or staff login.
    #[cfg_attr(
        feature = "schema",
        schemars(regex(pattern = "^[a-z0-9][a-z0-9._-]{0,63}$"))
    )]
    pub subject: String,
    /// Variable holding a separately generated 32-byte hexadecimal key.
    pub secret_env: EnvRef,
}

/// Resolve customer subjects to fixed-length verifiers. Private credentials never enter the journal.
///
/// # Errors
///
/// Rejects malformed subjects or secrets and credentials shared with other principals.
pub fn portal_credentials(
    users: &[PortalUser],
    env: &Env,
    operators: &Operators,
    service: Option<&Secret>,
) -> Result<BTreeMap<String, Token>, EstateError> {
    let mut found = BTreeMap::new();
    let mut used = std::collections::BTreeSet::new();
    for (index, user) in users.iter().enumerate() {
        let subject = user.subject.as_bytes();
        let error = |field: &str, reason: &str| EstateError::Invalid {
            key: format!("portal_users[{index}].{field}"),
            reason: reason.to_owned(),
        };
        if subject.is_empty()
            || subject.len() > 64
            || !subject[0].is_ascii_alphanumeric()
            || !subject.iter().all(|c| {
                c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, b'.' | b'_' | b'-')
            })
            || found.contains_key(&user.subject)
        {
            return Err(error(
                "subject",
                "expected a distinct lowercase customer subject (1–64 characters)",
            ));
        }
        let secret = user
            .secret_env
            .resolve_in(&format!("portal_users[{index}].secret_env"), env)?;
        let raw = secret.expose();
        if raw.len() != 64 || !raw.bytes().all(|c| c.is_ascii_hexdigit()) {
            return Err(error(
                "secret_env",
                "expected 32 randomly generated bytes in hexadecimal",
            ));
        }
        let verifier = hex::encode(Sha256::digest(raw.as_bytes()));
        if operators.identify(raw).is_some()
            || service.is_some_and(|s| s.expose() == raw)
            || !used.insert(verifier.clone())
        {
            return Err(error(
                "secret_env",
                "customer credentials must be unique and separate from staff and service credentials",
            ));
        }
        found.insert(user.subject.clone(), Token::new(&verifier));
    }
    Ok(found)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::Arc;

    #[test]
    fn customer_sign_in_credentials_are_separate_from_operator_and_service_credentials() {
        let key = "a1".repeat(32);
        let env: Env = Arc::new(|name| match name {
            "CUSTOMER" | "ALIAS" => Some("a1".repeat(32)),
            "WEAK" => Some("short".into()),
            _ => None,
        });
        let operators = Operators::new(vec![(
            crate::Actor::operator("billing").unwrap(),
            Token::new(&key),
        )]);
        let clerk = PortalUser {
            subject: "private-customer".into(),
            secret_env: EnvRef::new("CUSTOMER"),
        };
        for (ops, service) in [
            (&operators, None),
            (&Operators::default(), Some(Secret::new(&key))),
        ] {
            assert!(
                portal_credentials(std::slice::from_ref(&clerk), &env, ops, service.as_ref())
                    .is_err()
            );
        }
        let empty = Operators::default();
        assert!(portal_credentials(std::slice::from_ref(&clerk), &env, &empty, None).is_ok());
        for (subject, name) in [("duplicate", "ALIAS"), ("new", "WEAK"), ("-bad", "MISSING")] {
            let second = PortalUser {
                subject: subject.into(),
                secret_env: EnvRef::new(name),
            };
            let why = portal_credentials(&[clerk.clone(), second], &env, &empty, None)
                .unwrap_err()
                .to_string();
            assert!(!why.contains(&key));
        }
    }
}
