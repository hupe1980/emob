//! How a date, a time and an instant are written when a record leaves this
//! process.
//!
//! # The default is not a format
//!
//! `time`'s derived `Serialize` writes its own internal representation. An
//! `OffsetDateTime` becomes a nine-element array, a `Date` becomes
//! `[2026, 2]` — a year and an *ordinal day* — and a `Time` becomes
//! `[22, 0, 0, 0]`. They round-trip perfectly through `time`, which is why a
//! test that serialises and deserialises passes without noticing anything.
//!
//! Two things are wrong with that, and both matter for the artefact this
//! workspace exists to produce:
//!
//! - **A CDR is what two companies settle against.** A partner reading
//!   `"started_at": [2026, 2, 10, 0, 0, 0, 1, 0, 0]` cannot settle against it,
//!   and every wire this stack meets — OCPI, OCPP, OICP, EN 16931 — writes an
//!   instant as RFC 3339. A record only this codebase can read is not a record
//!   two parties hold.
//! - **The shape is a dependency's private business.** Nothing promises it will
//!   not change in a `time` release, and a settlement archive whose timestamps
//!   were written by one version and are read by another is a dispute nobody
//!   can resolve. `crate::TariffFingerprint` already refuses to let `time`
//!   format anything it hashes, for exactly this reason; the wire had the same
//!   exposure and no such defence.
//!
//! So every date and instant in a serialisable type goes through this module.
//! `OffsetDateTime` uses `time`'s own RFC 3339 support directly — it is
//! well-known and stable by definition — and [`date`] and [`clock`] are pinned
//! here to the ISO 8601 spellings the same standards use.
//!
//! ```
//! # #[cfg(feature = "serde")] {
//! use emob_core::QuarterHour;
//! use time::macros::datetime;
//!
//! let quarter = QuarterHour::containing(datetime!(2026-01-02 10:07 +1));
//! assert_eq!(
//!     serde_json::to_string(&quarter)?,
//!     r#""2026-01-02T10:00:00+01:00""#,
//! );
//! # }
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```

// `date` — a calendar date as `YYYY-MM-DD`: ISO 8601, and what every
// regulator's own document writes. The default is `[year, ordinal]`, which is
// not a date anybody reads.
/// A calendar date as `YYYY-MM-DD` — ISO 8601, and what every regulator's own
/// document writes.
///
/// `time`'s default is `[year, ordinal]`, which is not a date anybody reads.
///
/// Written out rather than generated by `time::serde::format_description!`,
/// which leaves its module private and therefore unusable from the other
/// crates that need to name it in a `serde(with = …)` path.
#[cfg(feature = "serde")]
pub mod date {
    use serde::{Deserialize as _, Deserializer, Serializer, de::Error as _};

    /// The one spelling, pinned here so no dependency chooses it.
    const FORMAT: &[time::format_description::FormatItem<'_>] =
        time::macros::format_description!("[year]-[month]-[day]");

    /// Write a date as `YYYY-MM-DD`.
    ///
    /// # Errors
    ///
    /// Whatever the serializer returns.
    pub fn serialize<S: Serializer>(value: &time::Date, serializer: S) -> Result<S::Ok, S::Error> {
        let text = value
            .format(FORMAT)
            .map_err(|e| serde::ser::Error::custom(e.to_string()))?;
        serializer.serialize_str(&text)
    }

    /// Read one back.
    ///
    /// # Errors
    ///
    /// [`serde::de::Error`] for text that is not a date in this spelling.
    pub fn deserialize<'de, D: Deserializer<'de>>(deserializer: D) -> Result<time::Date, D::Error> {
        let text = <std::borrow::Cow<'_, str>>::deserialize(deserializer)?;
        time::Date::parse(&text, FORMAT).map_err(D::Error::custom)
    }

    /// The same, for an optional date.
    pub mod option {
        use serde::{Deserialize as _, Deserializer, Serializer};

        /// Write an optional date, or null.
        ///
        /// # Errors
        ///
        /// Whatever the serializer returns.
        pub fn serialize<S: Serializer>(
            value: &Option<time::Date>,
            serializer: S,
        ) -> Result<S::Ok, S::Error> {
            match value {
                Some(date) => {
                    let text = date
                        .format(super::FORMAT)
                        .map_err(|e| serde::ser::Error::custom(e.to_string()))?;
                    serializer.serialize_some(&text)
                }
                None => serializer.serialize_none(),
            }
        }

        /// Read one back.
        ///
        /// # Errors
        ///
        /// [`serde::de::Error`] for text that is not a date in this spelling.
        pub fn deserialize<'de, D: Deserializer<'de>>(
            deserializer: D,
        ) -> Result<Option<time::Date>, D::Error> {
            use serde::de::Error as _;
            match Option::<std::borrow::Cow<'_, str>>::deserialize(deserializer)? {
                Some(text) => time::Date::parse(&text, super::FORMAT)
                    .map(Some)
                    .map_err(D::Error::custom),
                None => Ok(None),
            }
        }
    }
}

/// A time of day as `HH:MM:SS`.
