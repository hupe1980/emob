/// A duration as a whole number of seconds.
///
/// `time::Duration` serialises as `[seconds, nanoseconds]` by default. Every
/// duration this workspace puts on a wire is a session length or a clock
/// resolution — quantities `[REA 6-A §3.1]` and `[AFIR Art. 5(4)]` both discuss
/// in seconds and minutes — so the sub-second half is precision nobody asked
/// for wrapped around a shape nobody can read.
#[cfg(feature = "serde")]
pub mod duration_seconds {
    use serde::{Deserialize as _, Deserializer, Serializer};

    /// Write a duration as its whole seconds.
    ///
    /// # Errors
    ///
    /// Whatever the serializer returns.
    pub fn serialize<S: Serializer>(
        value: &time::Duration,
        serializer: S,
    ) -> Result<S::Ok, S::Error> {
        serializer.serialize_i64(value.whole_seconds())
    }

    /// Read one back.
    ///
    /// # Errors
    ///
    /// Whatever the deserializer returns.
    pub fn deserialize<'de, D: Deserializer<'de>>(
        deserializer: D,
    ) -> Result<time::Duration, D::Error> {
        i64::deserialize(deserializer).map(time::Duration::seconds)
    }

    /// The same, for an optional duration.
    pub mod option {
        use serde::{Deserialize as _, Deserializer, Serializer};

        /// Write an optional duration as whole seconds, or null.
        ///
        /// # Errors
        ///
        /// Whatever the serializer returns.
        pub fn serialize<S: Serializer>(
            value: &Option<time::Duration>,
            serializer: S,
        ) -> Result<S::Ok, S::Error> {
            match value {
                Some(duration) => serializer.serialize_some(&duration.whole_seconds()),
                None => serializer.serialize_none(),
            }
        }

        /// Read one back.
        ///
        /// # Errors
        ///
        /// Whatever the deserializer returns.
        pub fn deserialize<'de, D: Deserializer<'de>>(
            deserializer: D,
        ) -> Result<Option<time::Duration>, D::Error> {
            Ok(Option::<i64>::deserialize(deserializer)?.map(time::Duration::seconds))
        }
    }
}

/// A weekday by its English name, lower case.
///
/// `time::Weekday` serialises as a bare integer whose base is not stated
/// anywhere a reader of the JSON can see. `[OCPI 2.3.0 §Tariff]` writes the
/// day names, and a tariff restriction is a document a human argues about.
#[cfg(feature = "serde")]
pub mod weekday {
    use serde::{Deserialize as _, Deserializer, Serializer, de::Error as _};

    /// The seven names, in `time::Weekday`'s own order.
    const NAMES: [(&str, time::Weekday); 7] = [
        ("monday", time::Weekday::Monday),
        ("tuesday", time::Weekday::Tuesday),
        ("wednesday", time::Weekday::Wednesday),
        ("thursday", time::Weekday::Thursday),
        ("friday", time::Weekday::Friday),
        ("saturday", time::Weekday::Saturday),
        ("sunday", time::Weekday::Sunday),
    ];

    /// Write a weekday as its name.
    ///
    /// # Errors
    ///
    /// Whatever the serializer returns.
    #[allow(
        clippy::ptr_arg,
        reason = "serde's `with` contract passes the field type by reference, and the field is a Vec"
    )]
    pub fn serialize<S: Serializer>(
        value: &Vec<time::Weekday>,
        serializer: S,
    ) -> Result<S::Ok, S::Error> {
        let names: Vec<&str> = value
            .iter()
            .map(|day| {
                NAMES
                    .iter()
                    .find(|(_, d)| d == day)
                    .map_or("monday", |(name, _)| *name)
            })
            .collect();
        serde::Serialize::serialize(&names, serializer)
    }

    /// Read them back.
    ///
    /// # Errors
    ///
    /// [`serde::de::Error`] for a name outside the seven.
    pub fn deserialize<'de, D: Deserializer<'de>>(
        deserializer: D,
    ) -> Result<Vec<time::Weekday>, D::Error> {
        Vec::<String>::deserialize(deserializer)?
            .into_iter()
            .map(|name| {
                NAMES
                    .iter()
                    .find(|(n, _)| n.eq_ignore_ascii_case(&name))
                    .map(|(_, day)| *day)
                    .ok_or_else(|| D::Error::custom(format!("{name} is not a weekday")))
            })
            .collect()
    }
}

#[cfg(all(test, feature = "serde"))]
mod tests {
    use time::macros::{date, datetime, time as clock_time};

    #[derive(Debug, PartialEq, serde::Serialize, serde::Deserialize)]
    struct Sample {
        #[serde(with = "super::date")]
        on: time::Date,
        #[serde(with = "super::clock::option")]
        from: Option<time::Time>,
        #[serde(with = "super::duration_seconds")]
        lasted: time::Duration,
        #[serde(with = "super::weekday")]
        days: Vec<time::Weekday>,
        #[serde(with = "time::serde::rfc3339")]
        at: time::OffsetDateTime,
    }

    #[test]
    fn every_temporal_field_is_written_in_a_form_a_partner_can_read() {
        let sample = Sample {
            on: date!(2026 - 01 - 02),
            from: Some(clock_time!(22:00)),
            lasted: time::Duration::seconds(1800),
            days: vec![time::Weekday::Monday, time::Weekday::Sunday],
            at: datetime!(2026-01-02 10:00 +1),
        };
        let json = serde_json::to_string(&sample).unwrap();

        assert_eq!(
            json,
            concat!(
                r#"{"on":"2026-01-02","from":"22:00:00","lasted":1800,"#,
                r#""days":["monday","sunday"],"at":"2026-01-02T10:00:00+01:00"}"#,
            ),
            "a partner has to be able to read this without owning our types"
        );
        assert_eq!(serde_json::from_str::<Sample>(&json).unwrap(), sample);
    }

    #[test]
    fn an_absent_time_is_null_rather_than_an_empty_shape() {
        let sample = Sample {
            on: date!(2026 - 01 - 02),
            from: None,
            lasted: time::Duration::ZERO,
            days: Vec::new(),
            at: datetime!(2026-01-02 10:00 UTC),
        };
        let json = serde_json::to_string(&sample).unwrap();
        assert!(json.contains(r#""from":null"#), "{json}");
        assert!(json.contains(r#""at":"2026-01-02T10:00:00Z""#), "{json}");
        assert_eq!(serde_json::from_str::<Sample>(&json).unwrap(), sample);
    }

    #[test]
    fn a_name_outside_the_seven_is_refused() {
        let broken = r#"{"on":"2026-01-02","from":null,"lasted":0,"days":["funday"],"at":"2026-01-02T10:00:00Z"}"#;
        let error = serde_json::from_str::<Sample>(broken).unwrap_err();
        assert!(error.to_string().contains("not a weekday"), "{error}");
    }
}
